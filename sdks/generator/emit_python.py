def _generate_event_decoder(events: tuple[Event, ...]) -> list[str]:
    lines = _doclines(
        "Decodes a StreamPay contract event.\n\n"
        "Pass ``expected_contract_id`` to reject events from other contracts. "
        "System and diagnostic events are always ignored."
    )
    lines.append(
        "def decode_event("
        "event: ContractEvent, expected_contract_id: str | None = None"
        ") -> StreamPayEvent | None:"
    )
    lines.append("    if event.event_type != 1:")
    lines.append("        return None")
    lines.append("    if expected_contract_id is not None and event.contract != expected_contract_id:")
    lines.append("        return None")
    for index, event in enumerate(events):
        lines.append(f"    {'if' if index == 0 else 'elif'} event.name == {event.topic!r}:")
        lines.append(f"        if len(event.topics) != {len(event.topic_fields)}:")
        lines.append(
            f"            raise XdrError(f\"event {event.name} has {{len(event.topics)}} topics, "
            f"expected {len(event.topic_fields)}\")"
        )
        lines.append(f"        return {event.name}Event(")
        lines.append("            contract_id=event.contract,")
        for topic_index, item in enumerate(event.topic_fields):
            lines.append(
                f"            {item.name}=_decode_value({item.type.label!r}, "
                f"_event_topic(event, {topic_index}, {event.name!r})),"
            )
        for item in event.data_fields:
            lines.append(
                f"            {item.name}=_decode_value({item.type.label!r}, "
                f"_event_data(event, {event.name!r}, {item.name!r})),"
            )
        lines.append("        )")
    lines.append("    return None")
    lines.append("")
    return lines


def _registries(spec: SpecIR) -> list[str]:
    lines = ["_ENUM_TYPES = {"]
    for enum in spec.enums:
        lines.append(f"    {enum.name!r}: {enum.name},")
    lines += ["}", "", "_STRUCT_TYPES = {"]
    for struct in spec.structs:
        lines.append(f"    {struct.name!r}: {struct.name},")
    lines += ["}", "", "_UNION_TYPES = {"]
    for union in spec.unions:
        lines.append(f"    {union.name!r}: (")
        for case in union.cases:
            labels = tuple(item.label for item in case.types)
            lines.append(f"        ({case.name!r}, {union.name}{case.name}, {labels!r}),")
        lines.append("    ),")
    lines += ["}", ""]
    return lines


def generate_python() -> str:
    spec = _spec()
    lines = [HEADER.format(fingerprint=FINGERPRINT), '"""Typed StreamPay bindings generated from the canonical spec."""', "", "from __future__ import annotations", "", "from dataclasses import dataclass, field", "from enum import IntEnum", "from typing import Any, Callable, Final, TypeVar", "", "from .xdr import (", "    ContractEvent,", "    ScVal,", "    XdrError,", "    address_to_scval,", "    bool_to_scval,", "    i128_to_scval,", "    scval_to_address,", "    scval_to_bool,", "    scval_to_i128,", "    scval_to_struct,", "    scval_to_u64,", "    u64_to_scval,", ")", ""]
    lines.append(f'SPEC_FINGERPRINT = "{FINGERPRINT}"')
    lines.append(f"CONTRACT_VERSION: Final = {spec.contract.version!r}")
    for constant in spec.constants:
        lines.append(f"{constant.name}: Final = {constant.value}")
    lines += ["", "METHODS: Final[dict[str, str]] = {"]
    for function in spec.functions:
        lines.append(f"    {camel(function.name)!r}: {function.name!r},")
    lines += ["}", ""]

    lines.append("class StreamError(IntEnum):")
    for code, name in ERRORS:
        lines.append(f"    {name.upper()} = {code}")
    lines += [
        "",
        "",
        "CONTRACT_ERROR_NAMES: Final[dict[int, str]] = {",
    ]
    for code, name in ERRORS:
        lines.append(f"    {code}: {name!r},")
    lines += [
        "}",
        "",
        "",
        "def contract_error(code: int) -> StreamError | None:",
        "    try:",
        "        return StreamError(code)",
        "    except ValueError:",
        "        return None",
        "",
        "",
        "def contract_error_name(code: int) -> str | None:",
        "    return CONTRACT_ERROR_NAMES.get(code)",
        "",
        "",
    ]

    for enum in spec.enums:
        lines += _generate_enum(enum)
    for union in spec.unions:
        lines += _generate_union(union)
    for struct in spec.structs:
        lines += _generate_struct(struct)
    for function in spec.functions:
        lines += _generate_args(function)
    for event in spec.events:
        lines += _generate_event(event)
    lines.append("StreamPayEvent = (")
    for index, event in enumerate(spec.events):
        prefix = "    " if index == 0 else "    | "
        lines.append(f"{prefix}{event.name}Event")
    lines += [")", ""]

    lines += _RUNTIME.strip("\n").splitlines()
    lines.append("")
    lines += _registries(spec)
    lines += _generate_event_decoder(spec.events)
    for function in spec.functions:
        lines += _generate_decoder(function)

    lines.append("FUNCTIONS: Final[list[dict[str, Any]]] = [")
    for function in spec.functions:
        lines.append("    {")
        lines.append(f"        \"name\": {function.name!r},")
        lines.append(f"        \"arg_names\": {[item.name for item in function.args]!r},")
        lines.append(f"        \"arg_types\": {[item.type.label for item in function.args]!r},")
        lines.append(f"        \"return_type\": {function.returns.label!r},")
        lines.append(f"        \"mutating\": {function.mutating!r},")
        lines.append("    },")
    lines += ["]", ""]
    lines += _generate_read_methods(spec.read_functions)

    public = [
        "CONTRACT_VERSION",
        "METHODS",
        "SPEC_FINGERPRINT",
        "StreamError",
        "StreamPayEvent",
        "ReadOnlyMethods",
        "contract_error",
        "contract_error_name",
        "decode_event",
        *[constant.name for constant in spec.constants],
        *[item.name for item in spec.enums + spec.structs + spec.unions],
        *[f"{union.name}{case.name}" for union in spec.unions for case in union.cases],
        *[f"{event.name}Event" for event in spec.events],
        *[pascal(function.name) + "Args" for function in spec.functions if function.args],
        *[f"decode_{function.name}_result" for function in spec.functions],
    ]
    lines.append("__all__ = [")
    for name in sorted(set(public)):
        lines.append(f"    {name!r},")
    lines += ["]", ""]
    return "\n".join(lines)


def outputs(spec: SpecIR | dict, fingerprint: str, errors: list[tuple[int, str]]) -> dict[Path, str]:
    global SPEC, FINGERPRINT, ERRORS
    SPEC, FINGERPRINT, ERRORS = parse_spec(spec), fingerprint, errors
    return {PYTHON_PACKAGE / "_generated.py": generate_python()}
